#!/usr/bin/env python3
"""
TwinVolt Deployment Configuration Generator
============================================

Generates src/ui/js/config.js with backend URLs injected from environment variables.

Supports both variable naming conventions:
- TWINVOLT_API_BASE_URL / TWINVOLT_WS_BASE_URL
- VITE_API_BASE_URL / VITE_WS_BASE_URL

Usage:
    export TWINVOLT_API_BASE_URL="https://your-backend.railway.app"
    python scripts/build-config.py
"""

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG_OUT = ROOT / "src" / "ui" / "js" / "config.js"

api_base = (
    os.environ.get("TWINVOLT_API_BASE_URL")
    or os.environ.get("VITE_API_BASE_URL")
    or ""
).rstrip("/")

ws_base = (
    os.environ.get("TWINVOLT_WS_BASE_URL")
    or os.environ.get("VITE_WS_BASE_URL")
    or ""
).rstrip("/")

# Derive WS URL from API URL if not explicitly set
if not ws_base and api_base:
    ws_base = api_base.replace("https://", "wss://").replace("http://", "ws://")

if not api_base:
    print("[build-config] Neither TWINVOLT_API_BASE_URL nor VITE_API_BASE_URL set.")
    print("[build-config] Writing default same-origin placeholder config.js.")
else:
    print(f"[build-config] API base: {api_base}")
    print(f"[build-config] WS  base: {ws_base}")

config_content = f"""/**
 * TwinVolt Runtime Configuration Bridge — AUTO-GENERATED
 * Generated by: scripts/build-config.py
 *
 * Supports both TWINVOLT_* and VITE_* variable conventions.
 */
(function () {{
  'use strict';

  var apiBaseUrl = {repr(api_base) if api_base else "'__TWINVOLT_API_BASE_URL__'"};
  var wsBaseUrl  = {repr(ws_base) if ws_base else "'__TWINVOLT_WS_BASE_URL__'"};

  if (apiBaseUrl && apiBaseUrl !== '__TWINVOLT_API_BASE_URL__' && apiBaseUrl !== '__VITE_API_BASE_URL__') {{
    window.TWINVOLT_API_BASE_URL = apiBaseUrl;
    window.VITE_API_BASE_URL = apiBaseUrl;
  }}
  if (wsBaseUrl && wsBaseUrl !== '__TWINVOLT_WS_BASE_URL__' && wsBaseUrl !== '__VITE_WS_BASE_URL__') {{
    window.TWINVOLT_WS_BASE_URL = wsBaseUrl;
    window.VITE_WS_BASE_URL = wsBaseUrl;
  }}
}})();
"""

CONFIG_OUT.parent.mkdir(parents=True, exist_ok=True)
CONFIG_OUT.write_text(config_content, encoding="utf-8")
print(f"[build-config] Successfully written: {CONFIG_OUT}")
