#!/usr/bin/env python3
"""
TwinVolt Deployment Configuration Generator
============================================

This script generates src/ui/js/config.js with the actual backend URLs
injected from environment variables. Run this as part of your CI/CD
pipeline (GitHub Actions, Vercel build hook, etc.) BEFORE deploying
the frontend to Vercel.

Usage:
    # Set environment variables first:
    export TWINVOLT_API_BASE_URL="https://twinvolt-api.railway.app"
    export TWINVOLT_WS_BASE_URL="wss://twinvolt-api.railway.app"

    # Then run:
    python scripts/build-config.py

The script writes src/ui/js/config.js with the real URLs embedded.
Vercel then deploys this generated file as part of the static build output.

Notes:
- If TWINVOLT_API_BASE_URL is not set, config.js falls back to placeholder
  tokens and api.js uses relative URLs (safe for same-origin deployments).
- TWINVOLT_WS_BASE_URL is derived from API URL automatically if not set
  (http: → ws:, https: → wss:).
"""

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG_OUT = ROOT / "src" / "ui" / "js" / "config.js"

api_base = os.environ.get("TWINVOLT_API_BASE_URL", "").rstrip("/")
ws_base = os.environ.get("TWINVOLT_WS_BASE_URL", "").rstrip("/")

# Derive WS URL from API URL if not explicitly set
if not ws_base and api_base:
    ws_base = api_base.replace("https://", "wss://").replace("http://", "ws://")

if not api_base:
    print("[build-config] TWINVOLT_API_BASE_URL not set — writing placeholder config.js.")
    print("[build-config] Frontend will use relative URLs (same-origin mode).")
else:
    print(f"[build-config] API base: {api_base}")
    print(f"[build-config] WS  base: {ws_base}")

config_content = f"""/**
 * TwinVolt Runtime Configuration Bridge — AUTO-GENERATED
 * Generated by: scripts/build-config.py
 * Do NOT edit this file manually; it is regenerated at build time.
 *
 * To reconfigure, update your environment variables and re-run
 * python scripts/build-config.py  (or trigger your CI/CD pipeline).
 */
(function () {{
  'use strict';

  var apiBaseUrl = {repr(api_base) if api_base else "'__TWINVOLT_API_BASE_URL__'"};
  var wsBaseUrl  = {repr(ws_base) if ws_base else "'__TWINVOLT_WS_BASE_URL__'"};

  if (apiBaseUrl && apiBaseUrl !== '__TWINVOLT_API_BASE_URL__') {{
    window.TWINVOLT_API_BASE_URL = apiBaseUrl;
  }}
  if (wsBaseUrl && wsBaseUrl !== '__TWINVOLT_WS_BASE_URL__') {{
    window.TWINVOLT_WS_BASE_URL = wsBaseUrl;
  }}
}})();
"""

CONFIG_OUT.parent.mkdir(parents=True, exist_ok=True)
CONFIG_OUT.write_text(config_content, encoding="utf-8")
print(f"[build-config] Written: {CONFIG_OUT}")

